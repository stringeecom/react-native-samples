import StringeeCallManager from '../stringee_manager/StringeeCallManager';
import StringeeClientManager from '../stringee_manager/StringeeClientManager';

/**
 * Small application-facing facade around the Stringee SDK.
 *
 * UI code talks to this wrapper, while client/call managers own SDK lifecycle
 * and native CallKeep/notification synchronization.
 */
class StringeeWrapper {
  /** Shared facade used throughout the application. */
  static instance = new StringeeWrapper();

  /** @returns {import('stringee-react-native-v2').StringeeClient} Active SDK client. */
  get client() {
    return StringeeClientManager.instance.client;
  }

  /** @returns {object|null} Active call, or `null` when the app is idle. */
  get call() {
    return StringeeCallManager.instance.call;
  }

  /** @returns {boolean} Whether the Stringee client is connected. */
  get connected() {
    return this.client.isConnected;
  }

  /**
   * Installs the UI-level client listener.
   * @param {import('stringee-react-native-v2').StringeeClientListener} listener Listener to install.
   */
  setListener(listener) {
    StringeeClientManager.instance.listener = listener;
  }

  /**
   * Removes the listener only when it is still the active listener.
   * @param {import('stringee-react-native-v2').StringeeClientListener} listener Listener to remove.
   */
  removeListener(listener) {
    if (StringeeClientManager.instance.listener === listener) {
      StringeeClientManager.instance.listener = null;
    }
  }

  /**
   * Connects with a Stringee access token and persists it for push recovery.
   * @param {string} token Access token generated by a trusted server.
   * @returns {Promise<boolean>} Whether a connection attempt was accepted.
   */
  connect(token) {
    return StringeeClientManager.instance.connect(token);
  }

  /** Unregisters push, disconnects the client, and removes the saved token. */
  async disconnect() {
    try {
      await StringeeClientManager.instance.unregisterPush();
    } catch (error) {
      console.log('Unable to unregister push before disconnect', error);
    } finally {
      StringeeClientManager.instance.disconnect();
      await StringeeClientManager.instance.clearSavedAccessToken();
    }
  }

  /**
   * Starts an outgoing StringeeCall or StringeeCall2 session.
   * @param {{to: string, isVideoCall?: boolean, useCall2?: boolean}} options Call options.
   * @returns {Promise<object>} The initialized call instance.
   */
  makeCall({to, isVideoCall = false, useCall2 = false}) {
    return StringeeCallManager.instance.makeCall(
      this.client,
      to,
      isVideoCall,
      useCall2,
    );
  }
}

export default StringeeWrapper;
