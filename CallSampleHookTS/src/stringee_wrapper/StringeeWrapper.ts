import type {
  StringeeClient,
  StringeeClientListener,
} from 'stringee-react-native-v2';
import StringeeCallManager from '../stringee_manager/StringeeCallManager';
import StringeeClientManager from '../stringee_manager/StringeeClientManager';
import type {ActiveCall} from '../types';

export interface MakeCallOptions {
  to: string;
  isVideoCall?: boolean;
  useCall2?: boolean;
}

/**
 * Provides the application-facing facade for the local Stringee SDK.
 *
 * UI code uses this singleton for connection and outgoing-call operations,
 * while {@link StringeeClientManager} and {@link StringeeCallManager} retain
 * ownership of SDK, push, CallKeep, and notification lifecycle state.
 */
class StringeeWrapper {
  /** Shared facade used throughout the application. */
  static instance = new StringeeWrapper();

  /** Returns the active SDK client. */
  get client(): StringeeClient {
    return StringeeClientManager.instance.client;
  }

  /** Returns the active call, or `null` when the app is idle. */
  get call(): ActiveCall | null {
    return StringeeCallManager.instance.call;
  }

  /** Indicates whether the Stringee client is connected. */
  get connected(): boolean {
    return this.client.isConnected;
  }

  /** Installs the UI-level client listener. */
  setListener(listener: StringeeClientListener): void {
    StringeeClientManager.instance.listener = listener;
  }

  /** Removes the listener only when it is still the active listener. */
  removeListener(listener: StringeeClientListener): void {
    if (StringeeClientManager.instance.listener === listener) {
      StringeeClientManager.instance.listener = null;
    }
  }

  /**
   * Connects with a Stringee access token and persists it for push recovery.
   * @param token Access token generated by a trusted server.
   * @returns Whether a connection attempt was accepted.
   */
  connect(token: string): Promise<boolean> {
    return StringeeClientManager.instance.connect(token);
  }

  /** Unregisters push, disconnects the client, and removes the saved token. */
  async disconnect(): Promise<void> {
    try {
      await StringeeClientManager.instance.unregisterPush();
    } catch (error) {
      console.log('Unable to unregister push before disconnect', error);
    } finally {
      StringeeClientManager.instance.disconnect();
      await StringeeClientManager.instance.clearSavedAccessToken();
    }
  }

  /**
   * Starts an outgoing StringeeCall or StringeeCall2 session.
   * @param options Destination, media type, and SDK call implementation.
   * @returns The initialized call instance.
   */
  makeCall({
    to,
    isVideoCall = false,
    useCall2 = false,
  }: MakeCallOptions): Promise<ActiveCall> {
    return StringeeCallManager.instance.makeCall(
      this.client,
      to,
      isVideoCall,
      useCall2,
    );
  }
}

export default StringeeWrapper;
